export type SurfaceRouteMode = 'rail' | 'drive';

export interface SurfaceRouteStop {
  name: string;
  lat: number;
  lng: number;
}

export interface SurfaceRoute {
  id: string;
  mode: SurfaceRouteMode;
  title: string;
  stops: SurfaceRouteStop[];
  coordinates: [number, number][];
}

function distanceSquared(a: [number, number], b: [number, number]) {
  const lng = a[0] - b[0];
  const lat = a[1] - b[1];
  return lng * lng + lat * lat;
}

function smoothSegment(points: [number, number][], passes = 3): [number, number][] {
  if (points.length < 3) return points;
  let smoothed = points;
  for (let pass = 0; pass < passes; pass += 1) {
    const next: [number, number][] = [smoothed[0]];
    for (let index = 0; index < smoothed.length - 1; index += 1) {
      const from = smoothed[index];
      const to = smoothed[index + 1];
      next.push(
        [from[0] * .75 + to[0] * .25, from[1] * .75 + to[1] * .25],
        [from[0] * .25 + to[0] * .75, from[1] * .25 + to[1] * .75],
      );
    }
    next.push(smoothed[smoothed.length - 1]);
    smoothed = next;
  }
  return smoothed;
}

function smoothRailCoordinates(coordinates: [number, number][], stops: SurfaceRouteStop[]) {
  if (coordinates.length < 3) return coordinates;
  const anchorIndexes = stops
    .map((stop) => {
      const target: [number, number] = [stop.lng, stop.lat];
      let nearest = 0;
      for (let index = 1; index < coordinates.length; index += 1) {
        if (distanceSquared(coordinates[index], target) < distanceSquared(coordinates[nearest], target)) nearest = index;
      }
      return nearest;
    })
    .concat(0, coordinates.length - 1)
    .sort((a, b) => a - b)
    .filter((index, position, indexes) => position === 0 || index !== indexes[position - 1]);

  const smoothed: [number, number][] = [];
  for (let index = 0; index < anchorIndexes.length - 1; index += 1) {
    const from = anchorIndexes[index];
    const to = anchorIndexes[index + 1];
    const segment = smoothSegment(coordinates.slice(from, to + 1));
    smoothed.push(...(smoothed.length > 0 ? segment.slice(1) : segment));
  }
  return smoothed;
}

